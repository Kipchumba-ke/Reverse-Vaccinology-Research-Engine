BLOSUM62 = {
    (row_residue, column_residue): _ROWS[row_index][column_index]
    for row_index, row_residue in enumerate(_ORDER)
    for column_index, column_residue in enumerate(_ORDER)
}


def blosum62_score(residue_a: str, residue_b: str) -> int:
    """Return the BLOSUM62 score for two standard amino-acid letters."""
    try:
        return BLOSUM62[(residue_a, residue_b)]
    except KeyError as error:
        raise ValueError(
            f"No BLOSUM62 score for residues {residue_a!r} and {residue_b!r}."
        ) from error
